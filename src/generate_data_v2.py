def generate_normal_transactions(accounts, counterparty_pools, *, random_generator=None):
    """Generate baseline transactions with the original random draw order."""

    random_generator = rng if random_generator is None else random_generator

    transactions = []

    for account in accounts.itertuples(index=False):
        account_id = account.account_id
        inflow_mean, outflow_mean, amount_median = profile_parameters(
            account.activity_profile
        )

        for month in range(1, N_MONTHS + 1):
            n_in = int(random_generator.poisson(inflow_mean))
            n_out = int(random_generator.poisson(outflow_mean))

            for _ in range(n_in):
                amount = random_generator.lognormal(
                    mean=np.log(amount_median), sigma=0.65
                )
                transactions.append(
                    make_transaction(
                        account_id, month, "inflow", amount=amount,
                        counterparty_pools=counterparty_pools,
                        random_generator=random_generator,
                    )
                )

            for _ in range(n_out):
                amount = random_generator.lognormal(
                    mean=np.log(amount_median), sigma=0.65
                )
                transactions.append(
                    make_transaction(
                        account_id, month, "outflow", amount=amount,
                        counterparty_pools=counterparty_pools,
                        random_generator=random_generator,
                    )
                )

    return pd.DataFrame(transactions)


def generate_baseline(*, baseline_rng=None):
    """Generate an immutable baseline in memory; never inject or write files.

    A call without an explicit generator starts a fresh seed-42 baseline.
    Supplying a generator consumes only that generator, in the original order.
    IDs follow original baseline row order and do not consume random draws.
    """
    baseline_rng = np.random.default_rng(SEED) if baseline_rng is None else baseline_rng
    accounts = generate_accounts(random_generator=baseline_rng)
    counterparty_pools = generate_counterparty_pools(accounts)
    transactions = generate_normal_transactions(
        accounts, counterparty_pools, random_generator=baseline_rng
    )
    transactions.insert(
        0,
        "transaction_id",
        [f"TXN{i:07d}" for i in range(1, len(transactions) + 1)],
    )
    return BaselineSnapshot(
        _FrozenFrame.from_frame(accounts),
        tuple(
            (account_id, tuple(pool))
            for account_id, pool in counterparty_pools.items()
        ),
        _FrozenFrame.from_frame(transactions),
    )


