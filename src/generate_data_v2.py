def _valid_robust_scale(value):
    """No relative gates or artificial floor: finite and representably positive.

    Underflow to zero and nonfinite scales are invalid. Positive subnormal
    scales are allowed; any nonfinite resulting score remains unavailable.
    """
    return bool(np.isfinite(value) and value > 0)


def _historical_observation(past_values, current_value):
    """Analyze finite previous observations; never infer a zero-scale z-score."""
    past = np.asarray(past_values, dtype=float)
    finite_past = past[np.isfinite(past)]
    result = {
        "history_count": len(finite_past),
        "history_nonfinite_count": len(past) - len(finite_past),
        "history_median": np.nan, "history_mad": np.nan, "history_iqr": np.nan,
        "mad_scale": np.nan, "iqr_scale": np.nan, "selected_scale": np.nan,
        "scale_method": "unavailable", "signed_deviation": np.nan,
        "absolute_deviation": np.nan, "deviation_direction": "unknown",
        "constant_history": False, "constant_history_change": False,
        "robust_z": np.nan, "score_status": "insufficient_history",
    }
    if len(finite_past) < MIN_HISTORY:
        return result
    constant = bool(np.all(finite_past == finite_past[0]))
    result["constant_history"] = constant
    with np.errstate(over="ignore", invalid="ignore", divide="ignore", under="ignore"):
        if constant:
            # Avoid even-length median overflow for exactly equal large values.
            median, mad, iqr = float(finite_past[0]), 0.0, 0.0
        else:
            median = float(np.median(finite_past))
            mad = float(np.median(np.abs(finite_past - median)))
            q1, q3 = np.percentile(finite_past, [25, 75], method="linear")
            iqr = float(q3 - q1)
        mad_scale = float(np.float64(MAD_TO_SCALE) * mad)
        iqr_scale = float(np.float64(iqr) / IQR_TO_SCALE)
    for name, value in (
        ("history_median", median), ("history_mad", mad), ("history_iqr", iqr),
        ("mad_scale", mad_scale), ("iqr_scale", iqr_scale),
    ):
        result[name] = value if np.isfinite(value) else np.nan
    if not np.isfinite(median):
        result["score_status"] = "nonfinite_history_statistics"
        return result

    if np.isfinite(current_value):
        result["deviation_direction"] = (
            "increase" if current_value > median else "decrease" if current_value < median else "unchanged"
        )
        result["constant_history_change"] = bool(constant and current_value != median)
        with np.errstate(over="ignore", invalid="ignore"):
            deviation = float(np.float64(current_value) - median)
        if np.isfinite(deviation):
            result["signed_deviation"] = deviation
            result["absolute_deviation"] = abs(deviation)

    if _valid_robust_scale(mad_scale):
        scale, method = mad_scale, "MAD"
    elif _valid_robust_scale(iqr_scale):
        scale, method = iqr_scale, "IQR"
    else:
        result["score_status"] = "constant_history" if constant else "unavailable_scale"
        return result
    result["selected_scale"] = scale
    result["scale_method"] = method
    if not np.isfinite(current_value):
        result["score_status"] = "nonfinite_current"
        return result
    with np.errstate(over="ignore", invalid="ignore", divide="ignore", under="ignore"):
        score = float((np.float64(current_value) - median) / scale)
    if not np.isfinite(score):
        result["score_status"] = "nonfinite_score"
        return result
    result["robust_z"] = score
    result["score_status"] = "valid"
    return result


def compute_historical_statistics(aggregates):
    """Return numerical model features and separate long-form diagnostics.

    Histories are expanding and account-specific. NaN and infinity do not
    count toward the minimum of three observations. Current/future values
    never participate in the historical center or scale.
    """
    keys = ["account_id", "month"]
    required = keys + list(HISTORICAL_FEATURES)
    if any(column not in aggregates for column in required):
        raise ValueError("Historical input is missing required keys or features.")
    if aggregates[keys].isna().any().any() or aggregates.duplicated(keys).any():
        raise ValueError("Historical account-month keys must be present and unique.")
    # Whitelist numerical aggregates: labels and audit strings cannot propagate.
    model_columns = keys + [column for column in ACCOUNT_MONTH_BASE_COLUMNS if column in aggregates]
    features = aggregates[model_columns].sort_values(keys).reset_index(drop=True).copy()
    for feature in HISTORICAL_FEATURES:
        features[feature + "_change_vs_prev"] = np.nan
        features[feature + "_robust_z_past"] = np.nan
    diagnostics = []
    for account_id, group in features.groupby("account_id", sort=False):
        indices = group.index.to_numpy()
        months = group["month"].to_numpy()
        for feature in HISTORICAL_FEATURES:
            values = group[feature].to_numpy(dtype=float, na_value=np.nan)
            for position, index in enumerate(indices):
                current = values[position]
                if position and np.isfinite(current) and np.isfinite(values[position - 1]) and values[position - 1] != 0:
                    with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
                        change = (current - values[position - 1]) / abs(values[position - 1])
                    if np.isfinite(change):
                        features.at[index, feature + "_change_vs_prev"] = float(change)
                stats = _historical_observation(values[:position], current)
                features.at[index, feature + "_robust_z_past"] = stats["robust_z"]
                diagnostics.append({
                    "account_id": account_id, "month": months[position], "feature": feature, **stats,
                })
    diagnostic_columns = (
        "account_id", "month", "feature", "history_count", "history_nonfinite_count",
        "history_median", "history_mad", "history_iqr", "mad_scale", "iqr_scale",
        "selected_scale", "scale_method", "signed_deviation", "absolute_deviation",
        "deviation_direction", "constant_history", "constant_history_change",
        "robust_z", "score_status",
    )
    diagnostics = pd.DataFrame.from_records(diagnostics, columns=diagnostic_columns)
    diagnostics = diagnostics.sort_values(keys + ["feature"]).reset_index(drop=True)
    return features, diagnostics


def build_account_month_features(accounts, transactions):
    """Compatible numerical-only feature API; diagnostics have a separate API."""
    features, _ = compute_historical_statistics(
        build_account_month_aggregates(accounts, transactions)
    )
    return features


def compute_historical_decisions(features):
    """Feature-based strict decisions and coverage, independent of ground truth."""
    keys = ["account_id", "month"]
    columns = [feature + "_robust_z_past" for feature in HISTORICAL_FEATURES]
    if any(column not in features for column in keys + columns):
        raise ValueError("Historical decision input is missing keys or robust scores.")
    if features[keys].isna().any().any() or features.duplicated(keys).any():
        raise ValueError("Historical decision keys must be present and unique.")
    scores = features[columns].to_numpy(dtype=float, na_value=np.nan)
    finite = np.isfinite(scores)
    triggered = finite & (np.abs(scores) > HISTORICAL_SCORE_THRESHOLD)
    valid_count = finite.sum(axis=1).astype(int)
    result = features[keys].copy()
    result["is_history_anomaly"] = triggered.any(axis=1).astype(int)
    result["history_anomaly_reason"] = [
        ";".join(
            feature + (":increase" if score > 0 else ":decrease")
            for feature, score, flag in zip(HISTORICAL_FEATURES, row, flags) if flag
        )
        for row, flags in zip(scores, triggered)
    ]
    result["history_valid_score_count"] = valid_count
    result["history_assessment_status"] = np.where(
        valid_count == 0, "unassessed",
        np.where(valid_count == len(HISTORICAL_FEATURES), "complete", "partial"),
    )
    return result.sort_values(keys).reset_index(drop=True)


def add_historical_labels(features, labels):
    """Compute decisions without labels, then join them by account-month."""
    decisions = compute_historical_decisions(features)
    keys = ["account_id", "month"]
    if labels[keys].isna().any().any() or labels.duplicated(keys).any():
        raise ValueError("Ground-truth label keys must be present and unique.")
    if set(decisions.columns) & (set(labels.columns) - set(keys)):
        raise ValueError("Label table already contains historical decision fields.")
    result = labels.merge(
        decisions, on=keys, how="left", validate="one_to_one", indicator="_history_join"
    )
    if not result["_history_join"].eq("both").all():
        raise ValueError("Some label keys have no historical assessment.")
    return result.drop(columns="_history_join")

