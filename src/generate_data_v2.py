def dataframe_fingerprint(frame):
    """Version-specific deterministic digest of schema, row order, and values."""
    digest = hashlib.sha256()
    digest.update(repr(tuple(zip(frame.columns, map(str, frame.dtypes)))).encode("utf-8"))
    digest.update(pd.util.hash_pandas_object(frame, index=True).to_numpy(dtype=np.uint64).tobytes())
    return digest.hexdigest()


def _protected_file_hashes():
    """Read-only integrity checks; existing datasets never drive generation."""
    paths = [ROOT_DIR / "src" / "generate_data.py"]
    paths.extend(sorted(path for path in (ROOT_DIR / "data").rglob("*") if path.is_file()))
    return {
        path.relative_to(ROOT_DIR).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in paths
    }


def historical_comparison(labels):
    """Descriptive agreement only; unassessed rows enter no confusion cell.

    Partial assessments are included explicitly, not treated as complete.
    Metrics with zero denominators stay missing. No thresholds are fitted.
    """
    required = (
        "account_id", "month", "is_injected_anomaly", "is_history_anomaly",
        "history_valid_score_count", "history_assessment_status",
    )
    if any(column not in labels for column in required):
        raise ValueError("Comparison requires ground truth, historical decisions, and coverage.")
    if labels.duplicated(["account_id", "month"]).any():
        raise ValueError("Comparison keys must be unique.")
    for column in ("is_injected_anomaly", "is_history_anomaly"):
        if not labels[column].isin((0, 1)).all():
            raise ValueError("Comparison flags must be binary and present.")
    counts = labels["history_valid_score_count"]
    if not counts.isin(range(len(HISTORICAL_FEATURES) + 1)).all():
        raise ValueError("Invalid historical score coverage.")
    expected_status = np.where(
        counts.eq(0), "unassessed",
        np.where(counts.eq(len(HISTORICAL_FEATURES)), "complete", "partial"),
    )
    if not np.array_equal(labels["history_assessment_status"].to_numpy(), expected_status):
        raise ValueError("Historical status disagrees with score coverage.")
    if labels.loc[counts.eq(0), "is_history_anomaly"].ne(0).any():
        raise ValueError("An unassessed observation cannot have a robust-score alert.")
    scopes = [(f"month_{month}", (month,)) for month in INJECTION_MONTHS]
    scopes += [("overall_months_4_6", INJECTION_MONTHS), ("overall_months_1_6", tuple(range(1, N_MONTHS + 1)))]
    rows = []
    for scope, months in scopes:
        subset = labels.loc[labels["month"].isin(months)]
        assessed = subset.loc[subset["history_valid_score_count"].gt(0)]
        excluded = subset.loc[subset["history_valid_score_count"].eq(0)]
        truth = assessed["is_injected_anomaly"].eq(1)
        alert = assessed["is_history_anomaly"].eq(1)
        tp, fp = int((truth & alert).sum()), int((~truth & alert).sum())
        fn, tn = int((truth & ~alert).sum()), int((~truth & ~alert).sum())
        rows.append({
            "scope": scope, "comparison_population": "at_least_one_valid_score",
            "descriptive_only": True, "account_months": len(subset), "assessed": len(assessed),
            "unassessed": len(excluded),
            "partial": int(subset["history_assessment_status"].eq("partial").sum()),
            "complete": int(subset["history_assessment_status"].eq("complete").sum()),
            "coverage": len(assessed) / len(subset) if len(subset) else np.nan,
            "valid_scores": int(subset["history_valid_score_count"].sum()),
            "possible_scores": len(subset) * len(HISTORICAL_FEATURES),
            "unassessed_injected": int(excluded["is_injected_anomaly"].sum()),
            "unassessed_noninjected": int(excluded["is_injected_anomaly"].eq(0).sum()),
            "TP": tp, "FP": fp, "FN": fn, "TN": tn,
            "precision": tp / (tp + fp) if tp + fp else np.nan,
            "recall": tp / (tp + fn) if tp + fn else np.nan,
            "F1": 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else np.nan,
        })
    return pd.DataFrame.from_records(rows)


def _audit_row_state(context, row):
    if row is None:
        return {
            "timestamp": pd.NaT, "month": None, "debit_account": None,
            "credit_account": None, "amount_cents": None, "transaction_type": None, "channel": None,
        }
    return {
        "timestamp": row.timestamp, "month": context.month,
        "debit_account": row.counterparty if row.direction == "inflow" else context.account_id,
        "credit_account": context.account_id if row.direction == "inflow" else row.counterparty,
        "amount_cents": row.amount_cents, "transaction_type": row.transaction_type, "channel": row.channel,
    }


def _build_injection_audits(baseline, selected, transactions, allocation_seed):
    """Describe validated old-to-final changes, not fictional execution steps."""
    contexts = {
        (context.account_id, context.month): context
        for context in build_candidate_contexts(baseline, INJECTION_MONTHS)
    }
    indexed = transactions.set_index("transaction_id", drop=False)
    allocation, manifests, operations, invariants = [], [], [], []
    for plan in selected:
        context = contexts[(plan.account_id, plan.month)]
        plan_id = f"{plan.scenario[:2]}_{plan.account_id}_M{plan.month:02d}"
        expected_rows = _project_plan_rows(context, plan)
        ids = [row.transaction_id for row in expected_rows]
        actual = indexed.loc[ids].reset_index(drop=True)
        validate_candidate_plan(context, plan)
        _validate_applied_candidate(context, plan, actual)
        base = {
            "plan_id": plan_id, "account_id": plan.account_id, "month": plan.month,
            "scenario": plan.scenario, "activity_profile": plan.activity_profile,
        }
        allocation.append({
            **base, "allocation_seed": allocation_seed,
            "allocation_algorithm": "seeded_priority_augmenting_path_v1",
            "planning_seed_key": plan.planning_seed_key, "metadata_seed_key": plan.metadata_seed_key,
        })
        total, outgoing = _flow_cents(context.rows)
        final_total, final_outgoing = _flow_cents(expected_rows)
        originals = {row.transaction_id: row for row in context.rows}
        changed_direction = sum(
            row.direction != originals[row.transaction_id].direction for row in plan.updates
        )
        changed_direction += sum(
            row.direction != originals[row.donor_transaction_id].direction
            for row in plan.additions if row.donor_transaction_id is not None
        )
        metrics = dict(plan.diagnostics)
        manifests.append({
            **base, "planning_seed_key": plan.planning_seed_key, "metadata_seed_key": plan.metadata_seed_key,
            "baseline_count": len(context.rows), "final_count": len(expected_rows),
            "baseline_unique_counterparties": len({row.counterparty for row in context.rows}),
            "final_unique_counterparties": len({row.counterparty for row in expected_rows}),
            "baseline_total_cents": total, "final_total_cents": final_total,
            "baseline_inflow_cents": total - outgoing, "baseline_outflow_cents": outgoing,
            "final_inflow_cents": final_total - final_outgoing, "final_outflow_cents": final_outgoing,
            "baseline_outflow_share": outgoing / total, "final_outflow_share": final_outgoing / final_total,
            "pre_reversal_outflow_cents": metrics.get("pre_reversal_outflow_cents", outgoing) if plan.scenario in (SCENARIO_NAMES[2], SCENARIO_NAMES[4]) else None,
            "shift_sign": metrics.get("shift_sign"), "shift_denominator": metrics.get("shift_denominator"),
            "tolerance_denominator": metrics.get("tolerance_denominator"),
            "amount_numerator": 3 if plan.scenario == SCENARIO_NAMES[1] else 11 if plan.scenario == SCENARIO_NAMES[4] else 1,
            "amount_denominator": 10 if plan.scenario == SCENARIO_NAMES[4] else 1,
            "added_count": len(plan.additions), "updated_count": len(plan.updates),
            "reversed_count": changed_direction,
            "replaced_counterparty_count": sum(row.counterparty != originals[row.transaction_id].counterparty for row in plan.updates),
            "invariants_passed": True,
        })
        invariants.append({
            **base, "candidate_contract_passed": True, "actual_records_match_plan": True,
            "scenario_invariants_passed": True,
            "validation_method": "phase2_contract_and_phase3_actual_records",
        })
        for order, (old, new) in enumerate(
            [(originals[row.transaction_id], row) for row in plan.updates]
            + [(None, row) for row in plan.additions], 1
        ):
            tags = ["add"] if old is None else []
            if plan.scenario in (SCENARIO_NAMES[1], SCENARIO_NAMES[4]):
                tags.append("scale")
            direction_reference = old if old is not None else originals.get(new.donor_transaction_id)
            if direction_reference is not None and direction_reference.direction != new.direction:
                tags.append("reverse")
            if old is not None and old.counterparty != new.counterparty:
                tags.append("replace_counterparty")
            old_state, new_state = _audit_row_state(context, old), _audit_row_state(context, new)
            operations.append({
                **base, "operation_order": order, "transaction_id": new.transaction_id,
                "operation": "add" if old is None else "update", "action_tags": ";".join(tags),
                "donor_transaction_id": new.donor_transaction_id,
                **{"old_" + name: value for name, value in old_state.items()},
                **{"new_" + name: value for name, value in new_state.items()},
            })
    frames = {
        "selected_allocation": pd.DataFrame.from_records(allocation),
        "injection_manifest": pd.DataFrame.from_records(manifests),
        "applied_operations": pd.DataFrame.from_records(operations),
        "scenario_invariants": pd.DataFrame.from_records(invariants),
    }
    # Nullable integer columns preserve absent old states without float cents.
    for name in ("old_amount_cents", "new_amount_cents", "old_month", "new_month"):
        frames["applied_operations"][name] = pd.array(
            [row[name] for row in operations], dtype="Int64"
        )
    for name in ("pre_reversal_outflow_cents", "shift_sign", "shift_denominator", "tolerance_denominator"):
        frames["injection_manifest"][name] = pd.array(
            [row[name] for row in manifests], dtype="Int64"
        )
    return frames


def _historical_audit_tables(labels, diagnostics):
    decisions = labels[[
        "account_id", "month", "is_history_anomaly", "history_anomaly_reason",
        "history_valid_score_count", "history_assessment_status",
    ]].copy()
    rows = []
    for month in range(1, N_MONTHS + 1):
        d = diagnostics.loc[diagnostics["month"].eq(month)]
        h = decisions.loc[decisions["month"].eq(month)]
        departures = d.loc[d["constant_history_change"]]
        rows.append({
            "month": month, "account_months": len(h),
            "valid_scores": int(h["history_valid_score_count"].sum()),
            "possible_scores": len(h) * len(HISTORICAL_FEATURES),
            "unassessed": int(h["history_assessment_status"].eq("unassessed").sum()),
            "partial": int(h["history_assessment_status"].eq("partial").sum()),
            "complete": int(h["history_assessment_status"].eq("complete").sum()),
            "MAD_scores": int((d["scale_method"].eq("MAD") & d["robust_z"].notna()).sum()),
            "IQR_scores": int((d["scale_method"].eq("IQR") & d["robust_z"].notna()).sum()),
            "constant_departure_features": len(departures),
            "constant_departure_account_months": len(departures.drop_duplicates(["account_id", "month"])),
            "historical_alerts": int(h["is_history_anomaly"].sum()),
        })
    methods = diagnostics.groupby(
        ["month", "feature", "scale_method", "score_status"], sort=True
    ).size().rename("observations").reset_index()
    return {
        "historical_diagnostics": diagnostics,
        "historical_assessments": decisions,
        "historical_coverage": pd.DataFrame.from_records(rows),
        "historical_method_summary": methods,
        "constant_history_departures": diagnostics.loc[diagnostics["constant_history_change"]].reset_index(drop=True),
        "historical_comparison": historical_comparison(labels),
    }


def _validate_operation_audit(result):
    """Reconcile every old/new operation with baseline and applied records."""
    operations = result.audits["applied_operations"]
    before = result.baseline.transactions.set_index("transaction_id", drop=False)
    after = result.transactions.set_index("transaction_id", drop=False)
    expected_ids = {
        row.transaction_id for plan in result.selected_plans for row in plan.updates + plan.additions
    }
    if operations["transaction_id"].duplicated().any() or set(operations["transaction_id"]) != expected_ids:
        raise ValueError("Applied-operation audit is incomplete or duplicated.")
    for operation in operations.to_dict("records"):
        transaction_id = operation["transaction_id"]
        for prefix, indexed in (("old_", before), ("new_", after)):
            if prefix == "old_" and operation["operation"] == "add":
                if transaction_id in before.index:
                    raise ValueError("Audited addition already existed in the baseline.")
                if any(pd.notna(operation[prefix + name]) for name in ("timestamp", "month", "debit_account", "credit_account", "amount_cents", "transaction_type", "channel")):
                    raise ValueError("Addition audit invents an old state.")
                continue
            record = indexed.loc[transaction_id]
            for name in ("timestamp", "month", "debit_account", "credit_account", "transaction_type", "channel"):
                if operation[prefix + name] != record[name]:
                    raise ValueError(f"Operation audit disagrees with {prefix}{name}.")
            if operation[prefix + "amount_cents"] != amount_to_cents(record["amount"]):
                raise ValueError("Operation audit monetary values disagree with actual records.")


