def random_timestamp(month, *, random_generator=None):
    """Return a random timestamp within the configured month."""

    random_generator = rng if random_generator is None else random_generator

    year = START_YEAR
    calendar_month = START_MONTH + month - 1

    while calendar_month > 12:
        year += 1
        calendar_month -= 12

    last_day = calendar.monthrange(year, calendar_month)[1]
    day = int(random_generator.integers(1, last_day + 1))
    hour = int(random_generator.integers(0, 24))
    minute = int(random_generator.integers(0, 60))
    second = int(random_generator.integers(0, 60))

    return pd.Timestamp(
        year=year,
        month=calendar_month,
        day=day,
        hour=hour,
        minute=minute,
        second=second,
    )

def make_transaction(
    account_id,
    month,
    direction,
    amount=None,
    counterparty=None,
    counterparty_pools=None,
    *,
    random_generator=None,
):
    """
    Create one transaction involving one monitored account
    and one external counterparty.

    direction='inflow': external counterparty -> monitored account
    direction='outflow': monitored account -> external counterparty
    """

    random_generator = rng if random_generator is None else random_generator

    if counterparty is None:
        if counterparty_pools is None:
            raise ValueError(
                "counterparty_pools must be provided "
                "when counterparty is not specified."
            )

        counterparty = random_generator.choice(
            counterparty_pools[account_id]
        )

    if amount is None:
        amount = float(random_generator.lognormal(mean=7.2, sigma=0.8))

    amount = max(float(amount), 0.01)

    if direction == "inflow":
        debit_account = counterparty
        credit_account = account_id
        transaction_type = random_generator.choice(
            ["deposit", "transfer_in", "payment_in"]
        )
    else:
        debit_account = account_id
        credit_account = counterparty
        transaction_type = random_generator.choice(
            ["payment", "transfer_out", "bill_payment"]
        )

    return {
        "timestamp": random_timestamp(month, random_generator=random_generator),
        "month": month,
        "debit_account": debit_account,
        "credit_account": credit_account,
        "amount": round(amount, 2),
        "transaction_type": transaction_type,
        "channel": random_generator.choice(
            ["batch", "mobile", "web", "branch"]
        ),
    }

def profile_parameters(profile):
    """Return approximate monthly activity parameters for each profile."""

    parameters = {
        "low_activity": (3, 3, 2_500),
        "balanced": (14, 14, 2_000),
        "receiver": (25, 8, 5_000),
        "payer": (8, 25, 2_200),
        "high_activity": (30, 30, 1_800),
    }

    return parameters[profile]

