def _assert_no_reparse_components(path):
    """Reject symlinks/junctions, including existing ancestor components."""
    import stat
    path = Path(path).absolute()
    for component in (path,) + tuple(path.parents):
        if component.exists() or component.is_symlink():
            info = component.lstat()
            if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
                raise ValueError(f"Reparse points are forbidden in release paths: {component}")


def _windows_release_api():
    """No fallback: require local fixed NTFS with documented transaction support."""
    import ctypes
    from ctypes import wintypes
    if os.name != "nt":
        raise RuntimeError("Atomic publisher requires Windows NTFS transactions; no fallback.")
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    manager = ctypes.WinDLL("ktmw32", use_last_error=True)
    def bind(dll, name, args, result):
        function = getattr(dll, name)
        function.argtypes, function.restype = args, result
        return function
    return {
        "volume": bind(kernel, "GetVolumeInformationW", [
            wintypes.LPCWSTR, wintypes.LPWSTR, wintypes.DWORD,
            ctypes.POINTER(wintypes.DWORD), ctypes.POINTER(wintypes.DWORD),
            ctypes.POINTER(wintypes.DWORD), wintypes.LPWSTR, wintypes.DWORD,
        ], wintypes.BOOL),
        "drive_type": bind(kernel, "GetDriveTypeW", [wintypes.LPCWSTR], wintypes.UINT),
        "create": bind(manager, "CreateTransaction", [
            ctypes.c_void_p, ctypes.c_void_p, wintypes.DWORD, wintypes.DWORD,
            wintypes.DWORD, wintypes.DWORD, wintypes.LPWSTR,
        ], wintypes.HANDLE),
        "move": bind(kernel, "MoveFileTransactedW", [
            wintypes.LPCWSTR, wintypes.LPCWSTR, ctypes.c_void_p,
            ctypes.c_void_p, wintypes.DWORD, wintypes.HANDLE,
        ], wintypes.BOOL),
        "commit": bind(manager, "CommitTransaction", [wintypes.HANDLE], wintypes.BOOL),
        "rollback": bind(manager, "RollbackTransaction", [wintypes.HANDLE], wintypes.BOOL),
        "close": bind(kernel, "CloseHandle", [wintypes.HANDLE], wintypes.BOOL),
    }


def release_preflight():
    """Read-only preflight; any existing destination is protected, even if empty."""
    import ctypes
    from ctypes import wintypes
    root = ROOT_DIR.absolute()
    destination = root / "data" / "generated_v2" / "releases" / APPROVED_RELEASE_NAME
    _assert_no_reparse_components(destination)
    if root.resolve() != root or DATA_DIR.resolve() != root / "data" / "generated_v2":
        raise ValueError("Unexpected workspace or V2 root.")
    if destination.exists():
        state = "nonempty" if destination.is_dir() and any(destination.iterdir()) else "already present"
        raise FileExistsError(f"Release destination is {state}: {destination}; no replacement permitted.")
    api = _windows_release_api()
    volume_root = destination.anchor
    name, filesystem = ctypes.create_unicode_buffer(261), ctypes.create_unicode_buffer(261)
    serial, max_component, flags = wintypes.DWORD(), wintypes.DWORD(), wintypes.DWORD()
    if not api["volume"](
        volume_root, name, len(name), ctypes.byref(serial), ctypes.byref(max_component),
        ctypes.byref(flags), filesystem, len(filesystem),
    ):
        raise ctypes.WinError(ctypes.get_last_error())
    if api["drive_type"](volume_root) != 3 or filesystem.value != "NTFS" or not flags.value & 0x00200000:
        raise RuntimeError("Local fixed NTFS transaction support is required; refusing publication.")
    return destination


def _release_protected_snapshot():
    hashes = _protected_file_hashes()
    notebook = ROOT_DIR / "notebooks" / "02_model_preparation.ipynb"
    if notebook.exists():
        hashes[notebook.relative_to(ROOT_DIR).as_posix()] = hashlib.sha256(notebook.read_bytes()).hexdigest()
    original = ROOT_DIR / "data" / "generated"
    entries = tuple(sorted(path.relative_to(original).as_posix() for path in original.rglob("*")))
    return hashes, entries


def _verify_release_protection(snapshot, added_directory=None):
    hashes, entries = snapshot
    for relative, digest in hashes.items():
        path = ROOT_DIR / relative
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Protected file changed: {relative}")
    original = ROOT_DIR / "data" / "generated"
    if tuple(sorted(path.relative_to(original).as_posix() for path in original.rglob("*"))) != entries:
        raise ValueError("The strictly read-only research directory inventory changed.")
    data_files = {
        path.relative_to(ROOT_DIR).as_posix() for path in (ROOT_DIR / "data").rglob("*") if path.is_file()
    }
    expected = {relative for relative in hashes if relative.startswith("data/")}
    if added_directory is not None:
        expected |= {
            (added_directory / filename).relative_to(ROOT_DIR).as_posix()
            for filename in EXPECTED_RELEASE_FILENAMES
        }
    if data_files != expected:
        raise ValueError("Unexpected dataset creation, deletion, or relocation.")


def _release_expected_frames(result, prepared):
    frames = {filename: frame for filename, frame, _, _, _ in _export_table_definitions(result)}
    frames.update({"export_schema.csv": prepared.schema, "export_manifest.csv": prepared.manifest})
    return frames


def validate_release_directory(directory, result, prepared):
    """Read all disk bytes; validate hashes, typed frames, and actual interventions."""
    directory = Path(directory)
    _assert_no_reparse_components(directory)
    children = tuple(directory.iterdir())
    expected = set(EXPECTED_RELEASE_FILENAMES)
    if {path.name for path in children} != expected or any(not path.is_file() for path in children):
        raise ValueError("Release must contain exactly the 21 approved regular files.")
    expected_frames = _release_expected_frames(result, prepared)
    if set(prepared.payloads) != expected or set(expected_frames) != expected:
        raise ValueError("Prepared export file inventory changed.")
    manifest = prepared.manifest.set_index("filename")
    inventory = prepared.inventory.set_index("filename")
    loaded, hashes = {}, {}
    for filename in EXPECTED_RELEASE_FILENAMES:
        path = directory / filename
        _assert_no_reparse_components(path)
        payload = path.read_bytes()
        digest = hashlib.sha256(payload).hexdigest()
        if payload != prepared.payloads[filename] or digest != inventory.loc[filename, "csv_sha256"]:
            raise ValueError(f"Release byte hash mismatch: {filename}")
        if filename != "export_manifest.csv":
            if digest != manifest.loc[filename, "csv_sha256"] or len(payload) != manifest.loc[filename, "byte_count"]:
                raise ValueError(f"Export manifest mismatch: {filename}")
        schema = prepared.schema.loc[prepared.schema["filename"].eq(filename)]
        frame = deserialize_export_csv(payload, schema)
        pd.testing.assert_frame_equal(frame, expected_frames[filename], check_exact=True)
        key = schema.loc[schema["is_key"], "column"].tolist()
        if frame[key].isna().any().any() or frame.duplicated(key).any():
            raise ValueError(f"Missing or duplicate release key: {filename}")
        if filename != "export_manifest.csv" and dataframe_fingerprint(frame) != manifest.loc[filename, "table_fingerprint"]:
            raise ValueError(f"Typed release fingerprint mismatch: {filename}")
        loaded[filename], hashes[filename] = frame, digest
    validate_applied_injections(result.baseline, result.selected_plans, loaded["transactions.csv"])
    labels = loaded["evaluation_labels.csv"].merge(
        loaded["historical_assessments.csv"], on=["account_id", "month"], validate="one_to_one"
    )
    pd.testing.assert_frame_equal(labels, result.labels, check_exact=True)
    pd.testing.assert_frame_equal(
        compute_historical_decisions(loaded["account_month_features.csv"]),
        loaded["historical_assessments.csv"], check_exact=True,
    )
    return hashes


def _atomic_publish_staging(staging, destination):
    """A TxF commit atomically publishes the directory; never replace/copy/delete."""
    import ctypes
    approved = ROOT_DIR / "data" / "generated_v2" / "releases" / APPROVED_RELEASE_NAME
    prefix = f".{APPROVED_RELEASE_NAME}.staging-"
    suffix = staging.name.removeprefix(prefix)
    if destination != approved or not staging.name.startswith(prefix) or len(suffix) != 32 or any(c not in "0123456789abcdef" for c in suffix):
        raise ValueError("Atomic move is restricted to the approved release and owned staging namespace.")
    if staging.parent != destination.parent or staging.anchor != destination.anchor:
        raise ValueError("Staging must be a sibling on the same volume.")
    _assert_no_reparse_components(staging)
    _assert_no_reparse_components(destination)
    if destination.exists():
        raise FileExistsError("Release target appeared; refusing replacement.")
    api = _windows_release_api()
    transaction = api["create"](None, None, 0, 0, 0, 120000, "Validated V2 release publication")
    if transaction in (None, ctypes.c_void_p(-1).value):
        raise ctypes.WinError(ctypes.get_last_error())
    committed = False
    try:
        # WRITE_THROUGH only; neither REPLACE_EXISTING nor COPY_ALLOWED.
        if not api["move"](str(staging), str(destination), None, None, 0x8, transaction):
            raise ctypes.WinError(ctypes.get_last_error())
        if not api["commit"](transaction):
            raise ctypes.WinError(ctypes.get_last_error())
        committed = True
    finally:
        if not committed:
            api["rollback"](transaction)
        api["close"](transaction)


def publish_v2_release(result, prepared, *, authorize_sibling_staging=False):
    """Explicit publication only; failures retain unpublished staging for inspection."""
    import uuid
    if authorize_sibling_staging is not True:
        raise PermissionError("Sibling staging requires explicit authorization.")
    destination = release_preflight()
    snapshot = _release_protected_snapshot()
    metadata = result.audits["run_metadata"].set_index("key")["value"]
    if hashlib.sha256(Path(__file__).read_bytes()).hexdigest() != metadata["source_sha256"]:
        raise ValueError("Source changed after the validated pipeline run.")
    # Revalidate before creating anything. No seed changes, replanning, or fallback.
    validated = prepare_v2_exports(result)
    if validated.payloads != prepared.payloads:
        raise ValueError("Prepared CSV bytes disagree with fresh validated serialization.")
    pd.testing.assert_frame_equal(validated.schema, prepared.schema, check_exact=True)
    pd.testing.assert_frame_equal(validated.manifest, prepared.manifest, check_exact=True)
    _verify_release_protection(snapshot)
    destination = release_preflight()
    destination.parent.mkdir(exist_ok=True)
    _assert_no_reparse_components(destination.parent)
    staging = destination.parent / f".{APPROVED_RELEASE_NAME}.staging-{uuid.uuid4().hex}"
    staging.mkdir(exist_ok=False)
    committed = False
    try:
        for filename in EXPECTED_RELEASE_FILENAMES:
            path = staging / filename
            with path.open("xb") as handle:
                payload = prepared.payloads[filename]
                if handle.write(payload) != len(payload):
                    raise OSError(f"Short staged write: {filename}")
                handle.flush()
                os.fsync(handle.fileno())
        staged_hashes = validate_release_directory(staging, result, prepared)
        _verify_release_protection(snapshot, staging)
        if release_preflight() != destination:
            raise ValueError("Release destination changed.")
        _atomic_publish_staging(staging, destination)
        committed = True
        final_hashes = validate_release_directory(destination, result, prepared)
        if final_hashes != staged_hashes:
            raise ValueError("Published hashes differ from validated staged bytes.")
        _verify_release_protection(snapshot, destination)
        return {
            "status": "published_and_verified", "release_path": str(destination),
            "publication_method": "NTFS_transactional_directory_move_no_replace",
            "files": final_hashes, "file_count": len(final_hashes),
            "transactions": len(result.transactions), "account_months": len(result.features),
            "injected_account_months": int(result.labels["is_injected_anomaly"].sum()),
            "protected_files_unchanged": True, "staging_retained": staging.exists(),
        }
    except Exception as error:
        location = destination if committed else staging
        raise RuntimeError(
            f"Publication stopped; committed={committed}; inspection_path={location}; "
            "no overwrite, deletion, retry, or nontransactional fallback performed."
        ) from error


