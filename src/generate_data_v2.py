def generate_counterparty_pools(accounts):
    """Create a stable pool of potential counterparties for each account."""

    counterparty_pools = {}

    for account_id in accounts["account_id"]:
        account_number = int(account_id[3:])

        counterparty_pools[account_id] = [
            f"CP{account_number:05d}_{i:03d}"
            for i in range(1, COUNTERPARTY_POOL_SIZE + 1)
        ]

    return counterparty_pools
