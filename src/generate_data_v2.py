def amount_to_cents(amount):
    """Read finite, positive, already cent-rounded baseline amounts exactly."""
    value = Decimal(str(amount))
    cents = value * 100
    if not value.is_finite() or cents <= 0 or cents != cents.to_integral_value():
        raise ValueError("Baseline amount must be finite, positive, and cent-rounded.")
    return int(cents)


def scale_cents_half_even(cents, numerator=11, denominator=10):
    """Exact rational scaling with round-half-to-even, no float arithmetic."""
    if not isinstance(cents, (int, np.integer)) or cents <= 0:
        raise ValueError("Cents must be a positive integer.")
    if not isinstance(numerator, int) or not isinstance(denominator, int):
        raise ValueError("Scaling numerator and denominator must be integers.")
    if numerator <= 0 or denominator <= 0:
        raise ValueError("Scaling numerator and denominator must be positive.")
    quotient, remainder = divmod(int(cents) * numerator, denominator)
    if 2 * remainder > denominator or (2 * remainder == denominator and quotient % 2):
        quotient += 1
    return quotient


def candidate_seed_key(context, scenario, root_seed):
    if scenario not in SCENARIO_NAMES:
        raise ValueError("Unknown scenario.")
    if not context.account_id.startswith("ACC") or not context.account_id[3:].isdigit():
        raise ValueError("Candidate accounts must use ACC followed by digits.")
    return (root_seed, int(context.account_id[3:]), context.month, SCENARIO_NAMES.index(scenario) + 1)


def _flow_cents(rows):
    total = sum(row.amount_cents for row in rows)
    outflow = sum(row.amount_cents for row in rows if row.direction == "outflow")
    return total, outflow


def _check_candidate_rows(context, rows):
    if not 1 <= context.month <= N_MONTHS:
        raise ValueError("Candidate month is outside the configured period.")
    if len({row.transaction_id for row in rows}) != len(rows):
        raise ValueError("Duplicate candidate transaction identity.")
    if not {row.counterparty for row in context.rows} <= context.external_ids:
        raise ValueError("Baseline external-ID registry omits observed counterparties.")
    expected_month = pd.Timestamp(year=START_YEAR, month=START_MONTH, day=1) + pd.DateOffset(months=context.month - 1)
    for row in rows:
        if not isinstance(row.amount_cents, (int, np.integer)) or row.amount_cents <= 0:
            raise ValueError("Planned amounts must be positive integer cents.")
        allowed_types = _INFLOW_TYPES if row.direction == "inflow" else _OUTFLOW_TYPES
        if row.direction not in ("inflow", "outflow") or row.transaction_type not in allowed_types:
            raise ValueError("Direction and transaction type disagree.")
        if not isinstance(row.counterparty, str) or not row.counterparty or row.counterparty.startswith("ACC"):
            raise ValueError("Counterparty must be an external ID.")
        if row.channel not in ("batch", "mobile", "web", "branch"):
            raise ValueError("Invalid transaction channel.")
        if pd.isna(row.timestamp) or (row.timestamp.year, row.timestamp.month) != (expected_month.year, expected_month.month):
            raise ValueError("Timestamp disagrees with candidate month.")


def build_candidate_contexts(baseline, months=(4, 5, 6)):
    """Index defensive baseline copies; sort stable IDs for order independence."""
    months = tuple(months)
    if len(set(months)) != len(months) or any(month not in range(1, N_MONTHS + 1) for month in months):
        raise ValueError("Months must be distinct configured month numbers.")
    accounts = baseline.accounts
    profiles = dict(zip(accounts["account_id"], accounts["activity_profile"]))
    transactions = baseline.transactions
    if not transactions["transaction_id"].is_unique:
        raise ValueError("Baseline transaction IDs must be unique.")
    grouped = {}
    external_ids = set()
    for row in transactions.itertuples(index=False):
        debit_monitored = row.debit_account in profiles
        credit_monitored = row.credit_account in profiles
        if debit_monitored == credit_monitored:
            raise ValueError("Each baseline row must involve exactly one monitored account.")
        account_id = row.debit_account if debit_monitored else row.credit_account
        counterparty = row.credit_account if debit_monitored else row.debit_account
        if not isinstance(counterparty, str) or counterparty.startswith("ACC"):
            raise ValueError("External endpoint uses a monitored-account prefix.")
        external_ids.add(counterparty)
        if row.month in months:
            planned = PlannedTransaction(
                row.transaction_id, amount_to_cents(row.amount),
                "outflow" if debit_monitored else "inflow", counterparty,
                row.transaction_type, row.timestamp, row.channel,
            )
            grouped.setdefault((account_id, row.month), []).append(planned)
    external_ids = frozenset(external_ids)
    contexts = []
    for account_id in sorted(profiles):
        for month in months:
            context = CandidateMonth(
                account_id, month, profiles[account_id],
                tuple(sorted(grouped.get((account_id, month), ()), key=lambda row: row.transaction_id)),
                external_ids,
            )
            _check_candidate_rows(context, context.rows)
            contexts.append(context)
    return tuple(contexts)


def _reverse_planned_row(row):
    return replace(
        row,
        direction="outflow" if row.direction == "inflow" else "inflow",
        transaction_type=_REVERSED_TYPES[row.transaction_type],
    )


def _added_id(context, scenario, ordinal):
    return f"CAND_{scenario[:2]}_{context.account_id}_M{context.month:02d}_{ordinal:06d}"


def _prefix_reversal(rows, sign, delta_denominator, tolerance_denominator, random):
    """Nearest bracketing prefix; all amount and tolerance comparisons exact.

    delta = sign / delta_denominator and tolerance = 1 / tolerance_denominator.
    A failed single permutation is not proof that every possible subset fails.
    """
    total, _ = _flow_cents(rows)
    if total == 0:
        return (), False
    source_direction = "inflow" if sign > 0 else "outflow"
    indices = np.array([i for i, row in enumerate(rows) if row.direction == source_direction], dtype=int)
    order = random.permutation(indices)
    cumulative = [0]
    for index in order:
        cumulative.append(cumulative[-1] + rows[int(index)].amount_cents)
    upper = bisect_left([delta_denominator * value for value in cumulative], total)
    choices = {max(0, min(len(order), upper - 1)), max(0, min(len(order), upper))}
    length = min(choices, key=lambda k: (abs(delta_denominator * cumulative[k] - total), k))
    error = abs(delta_denominator * cumulative[length] - total)
    ok = length > 0 and error * tolerance_denominator <= delta_denominator * total
    return tuple(int(index) for index in order[:length]), ok


def _plan_s1(context, random, metadata):
    if not context.rows:
        return (), (), ("zero_transactions",), ()
    median = profile_parameters(context.activity_profile)[2]
    counterparties = sorted({row.counterparty for row in context.rows})
    additions = []
    for direction, allowed_types in (("inflow", _INFLOW_TYPES), ("outflow", _OUTFLOW_TYPES)):
        quota = sum(row.direction == direction for row in context.rows)
        for _ in range(quota):
            # Independent draws use precisely the baseline profile amount law.
            amount = round(max(float(random.lognormal(np.log(median), 0.65)), 0.01), 2)
            counterparty = str(random.choice(counterparties))
            additions.append(PlannedTransaction(
                _added_id(context, SCENARIO_NAMES[0], len(additions) + 1),
                amount_to_cents(amount), direction, counterparty,
                str(metadata.choice(allowed_types)),
                random_timestamp(context.month, random_generator=metadata),
                str(metadata.choice(("batch", "mobile", "web", "branch"))),
            ))
    return (), tuple(additions), (), (("profile_amount_median", median), ("profile_amount_sigma", 0.65))


def _plan_s2(context, random, metadata):
    if not context.rows:
        return (), (), ("zero_transactions",), ()
    updates = tuple(replace(row, amount_cents=3 * row.amount_cents) for row in context.rows)
    return updates, (), (), (("amount_numerator", 3), ("amount_denominator", 1))


def _plan_s3(context, random, metadata):
    if not context.rows:
        return (), (), ("zero_transactions",), ()
    total, outflow = _flow_cents(context.rows)
    sign = 1 if 10 * outflow <= 7 * total else -1
    indices, ok = _prefix_reversal(context.rows, sign, 5, 20, random)
    updates = tuple(_reverse_planned_row(context.rows[i]) for i in indices)
    final_outflow = outflow + sign * sum(context.rows[i].amount_cents for i in indices)
    metrics = (
        ("total_cents", total), ("baseline_outflow_cents", outflow),
        ("projected_outflow_cents", final_outflow), ("shift_sign", sign),
        ("shift_denominator", 5), ("tolerance_denominator", 20),
    )
    return updates, (), (() if ok else ("prefix_shift_outside_tolerance",)), metrics


def _plan_s4(context, random, metadata):
    counts = Counter(row.counterparty for row in context.rows)
    n, unique = len(context.rows), len(counts)
    if n == unique:
        return (), (), ("no_duplicate_counterparties",), ()
    k = min(n - unique, max(1, (unique + 1) // 2))
    retained = set()
    replaceable = []
    for row in context.rows:
        if row.counterparty in retained:
            replaceable.append(row)
        else:
            retained.add(row.counterparty)
    chosen = random.choice(len(replaceable), size=k, replace=False)
    updates = []
    for ordinal, position in enumerate(chosen, 1):
        # Deterministic, candidate-specific IDs, checked against all baseline IDs.
        suffix = ordinal
        counterparty = f"EXTV2_{context.account_id}_M{context.month:02d}_{suffix:06d}"
        while counterparty in context.external_ids or any(row.counterparty == counterparty for row in updates):
            suffix += 1
            counterparty = f"EXTV2_{context.account_id}_M{context.month:02d}_{suffix:06d}"
        updates.append(replace(replaceable[int(position)], counterparty=counterparty))
    return tuple(updates), (), (), (("diversity_increase", k),)


def _plan_s5(context, random, metadata):
    n = len(context.rows)
    if n < 20:
        return (), (), ("fewer_than_20_transactions",), ()
    outgoing = np.array([i for i, row in enumerate(context.rows) if row.direction == "outflow"], dtype=int)
    incoming = np.array([i for i, row in enumerate(context.rows) if row.direction == "inflow"], dtype=int)
    if not len(outgoing) or not len(incoming):
        return (), (), ("missing_direction",), ()
    added_count = n // 5
    added_out = (2 * added_count * len(outgoing) + n) // (2 * n)
    added_in = added_count - added_out
    donors = tuple(int(i) for i in np.concatenate((
        random.choice(outgoing, size=added_out, replace=True),
        random.choice(incoming, size=added_in, replace=True),
    )))
    additions = tuple(replace(
        context.rows[index],
        transaction_id=_added_id(context, SCENARIO_NAMES[4], ordinal),
        timestamp=random_timestamp(context.month, random_generator=metadata),
        donor_transaction_id=context.rows[index].transaction_id,
    ) for ordinal, index in enumerate(donors, 1))
    projected = tuple(
        replace(row, amount_cents=scale_cents_half_even(row.amount_cents))
        for row in context.rows + additions
    )
    baseline_total, baseline_outflow = _flow_cents(context.rows)
    total, before_reversal_outflow = _flow_cents(projected)
    sign = 1 if 2 * before_reversal_outflow <= total else -1
    indices, prefix_ok = _prefix_reversal(projected, sign, 20, 50, random)
    reversed_indices = set(indices)
    projected = tuple(_reverse_planned_row(row) if i in reversed_indices else row for i, row in enumerate(projected))
    _, final_outflow = _flow_cents(projected)
    failures = []
    if added_count * 20 < 3 * n or added_count * 5 > n:
        failures.append("count_increase_outside_bounds")
    if total * 5 > baseline_total * 7:
        failures.append("total_amount_increase_above_40_percent")
    if not prefix_ok:
        failures.append("prefix_shift_outside_tolerance")
    if final_outflow * 10 < total or final_outflow * 10 > 9 * total:
        failures.append("directional_share_outside_bounds")
    metrics = (
        ("baseline_total_cents", baseline_total), ("baseline_outflow_cents", baseline_outflow),
        ("projected_total_cents", total), ("pre_reversal_outflow_cents", before_reversal_outflow),
        ("projected_outflow_cents", final_outflow), ("added_count", added_count),
        ("added_outflow_quota", added_out), ("added_inflow_quota", added_in),
        ("reversed_count", len(indices)), ("shift_sign", sign),
        ("shift_denominator", 20), ("tolerance_denominator", 50),
        ("scaling_rounding", "integer_half_even"),
    )
    return projected[:n], projected[n:], tuple(failures), metrics


def _project_plan_rows(context, plan):
    """Project immutable scalar descriptions only; never edit a DataFrame."""
    updates = {row.transaction_id: row for row in plan.updates}
    return tuple(updates.get(row.transaction_id, row) for row in context.rows) + plan.additions


def validate_candidate_plan(context, plan):
    """Raise on broken intervention invariants; rejection is not success."""
    if (plan.account_id, plan.month, plan.activity_profile) != (context.account_id, context.month, context.activity_profile):
        raise ValueError("Plan does not belong to the baseline context.")
    if plan.scenario not in SCENARIO_NAMES or plan.eligible != (not plan.rejection_reasons):
        raise ValueError("Invalid scenario or eligibility status.")
    _check_candidate_rows(context, context.rows)
    if not plan.eligible:
        if plan.updates or plan.additions:
            raise ValueError("Rejected candidates must expose no executable operations.")
        return
    originals = {row.transaction_id: row for row in context.rows}
    update_ids = [row.transaction_id for row in plan.updates]
    if len(set(update_ids)) != len(update_ids) or not set(update_ids) <= originals.keys():
        raise ValueError("Updates must reference distinct baseline IDs.")
    if any(row.transaction_id in originals for row in plan.additions):
        raise ValueError("Added IDs collide with baseline IDs.")
    projected = _project_plan_rows(context, plan)
    _check_candidate_rows(context, projected)
    n, unique = len(context.rows), len({row.counterparty for row in context.rows})
    total, outflow = _flow_cents(context.rows)
    final_total, final_outflow = _flow_cents(projected)
    final_originals = projected[:n]
    scenario = SCENARIO_NAMES.index(plan.scenario) + 1
    if scenario == 1:
        if not n or plan.updates or len(projected) != 2 * n:
            raise ValueError("S1 count or preservation invariant failed.")
        for direction in ("inflow", "outflow"):
            if sum(row.direction == direction for row in plan.additions) != sum(row.direction == direction for row in context.rows):
                raise ValueError("S1 direction quota failed.")
        if not {row.counterparty for row in plan.additions} <= {row.counterparty for row in context.rows}:
            raise ValueError("S1 introduced an unobserved counterparty.")
    elif scenario == 2:
        if not n or plan.additions or final_originals != tuple(replace(row, amount_cents=3 * row.amount_cents) for row in context.rows):
            raise ValueError("S2 amount-only invariant failed.")
    elif scenario == 3:
        sign = 1 if 10 * outflow <= 7 * total else -1
        source_direction = "inflow" if sign > 0 else "outflow"
        changed = 0
        for old, new in zip(context.rows, final_originals):
            if new != old:
                if new != _reverse_planned_row(old) or old.direction != source_direction:
                    raise ValueError("S3 changed more than direction and type.")
                changed += 1
        sign = 1 if 10 * outflow <= 7 * total else -1
        transfer = sign * (final_outflow - outflow)
        if plan.additions or final_total != total or not changed or transfer <= 0 or abs(5 * transfer - total) * 20 > 5 * total:
            raise ValueError("S3 flow-shift invariant failed.")
    elif scenario == 4:
        k = min(n - unique, max(1, (unique + 1) // 2))
        changed = []
        for old, new in zip(context.rows, final_originals):
            if replace(new, counterparty=old.counterparty) != old:
                raise ValueError("S4 changed a non-counterparty field.")
            if new.counterparty != old.counterparty:
                changed.append(new.counterparty)
        final_counterparties = {row.counterparty for row in projected}
        if plan.additions or k <= 0 or len(changed) != k or len(set(changed)) != k:
            raise ValueError("S4 replacement-count invariant failed.")
        if set(changed) & context.external_ids or not {row.counterparty for row in context.rows} <= final_counterparties or len(final_counterparties) != unique + k:
            raise ValueError("S4 diversity invariant failed.")
    elif scenario == 5:
        if n < 20 or not any(row.direction == "inflow" for row in context.rows) or not any(row.direction == "outflow" for row in context.rows):
            raise ValueError("S5 baseline eligibility failed.")
        added_count = n // 5
        outgoing = sum(row.direction == "outflow" for row in context.rows)
        expected_added_out = (2 * added_count * outgoing + n) // (2 * n)
        if len(plan.additions) != added_count or added_count * 20 < 3 * n or added_count * 5 > n or 5 * final_total > 7 * total:
            raise ValueError("S5 count or total-amount bound failed.")
        pre_reversal = []
        reversal_count = 0
        donor_directions = []
        for old, new in zip(context.rows, final_originals):
            expected = replace(old, amount_cents=scale_cents_half_even(old.amount_cents))
            if new not in (expected, _reverse_planned_row(expected)):
                raise ValueError("S5 changed an original row outside its contract.")
            pre_reversal.append(expected)
            reversal_count += new.direction != expected.direction
        for new in plan.additions:
            donor = originals.get(new.donor_transaction_id)
            if donor is None:
                raise ValueError("S5 addition has no baseline donor.")
            expected = replace(
                donor, amount_cents=scale_cents_half_even(donor.amount_cents),
                transaction_id=new.transaction_id, timestamp=new.timestamp,
                donor_transaction_id=donor.transaction_id,
            )
            if new not in (expected, _reverse_planned_row(expected)):
                raise ValueError("S5 donor attributes or scaling changed.")
            pre_reversal.append(expected)
            donor_directions.append(donor.direction)
            reversal_count += new.direction != expected.direction
        if donor_directions.count("outflow") != expected_added_out:
            raise ValueError("S5 donor direction quota failed.")
        _, pre_outflow = _flow_cents(pre_reversal)
        sign = 1 if 2 * pre_outflow <= final_total else -1
        source_direction = "inflow" if sign > 0 else "outflow"
        if any(old.direction != source_direction for old, new in zip(pre_reversal, projected) if old.direction != new.direction):
            raise ValueError("S5 reversed a row from the wrong source direction.")
        transfer = sign * (final_outflow - pre_outflow)
        if not reversal_count or transfer <= 0 or abs(20 * transfer - final_total) * 50 > 20 * final_total:
            raise ValueError("S5 directional shift failed.")
        if 10 * final_outflow < final_total or 10 * final_outflow > 9 * final_total:
            raise ValueError("S5 final directional-share bound failed.")


def plan_candidate(context, scenario, *, planning_seed=PLANNING_SEED, metadata_seed=METADATA_SEED):
    """Plan one reproducible candidate without consuming shared RNG state."""
    _check_candidate_rows(context, context.rows)
    planning_key = candidate_seed_key(context, scenario, planning_seed)
    metadata_key = candidate_seed_key(context, scenario, metadata_seed)
    random = np.random.default_rng(np.random.SeedSequence(planning_key))
    metadata = np.random.default_rng(np.random.SeedSequence(metadata_key))
    planner = (_plan_s1, _plan_s2, _plan_s3, _plan_s4, _plan_s5)[SCENARIO_NAMES.index(scenario)]
    updates, additions, failures, diagnostics = planner(context, random, metadata)
    plan = CandidatePlan(
        context.account_id, context.month, context.activity_profile, scenario,
        planning_key, metadata_key, not failures, failures,
        updates if not failures else (), additions if not failures else (), diagnostics,
    )
    validate_candidate_plan(context, plan)
    return plan


def build_candidate_plans(baseline, months=(4, 5, 6), *, planning_seed=PLANNING_SEED, metadata_seed=METADATA_SEED):
    """Return all candidates, not selected accounts or an injected dataset."""
    return tuple(
        plan_candidate(context, scenario, planning_seed=planning_seed, metadata_seed=metadata_seed)
        for context in build_candidate_contexts(baseline, months)
        for scenario in SCENARIO_NAMES
    )


