def generate_accounts(*, random_generator=None):
    """Create synthetic accounts with the original random draw order."""

    random_generator = rng if random_generator is None else random_generator

    profiles = ["balanced", "receiver", "payer", "low_activity", "high_activity"]
    probabilities = [0.30, 0.20, 0.20, 0.10, 0.20]

    account_ids = [f"ACC{i:05d}" for i in range(1, N_ACCOUNTS + 1)]

    accounts = pd.DataFrame(
        {
            "account_id": account_ids,
            "account_type": random_generator.choice(
                ["personal", "business"], size=N_ACCOUNTS, p=[0.85, 0.15]
            ),
            "activity_profile": random_generator.choice(
                profiles, size=N_ACCOUNTS, p=probabilities
            ),
        }
    )

    return accounts
