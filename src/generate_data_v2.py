def _export_schema_rows(filename, frame, primary_key):
    if not frame.columns.is_unique or not set(primary_key) <= set(frame.columns):
        raise ValueError("Export columns and primary key are invalid.")
    if frame[list(primary_key)].isna().any().any() or frame.duplicated(list(primary_key)).any():
        raise ValueError(f"Missing or duplicate export key: {filename}")
    if not frame.index.equals(pd.RangeIndex(len(frame))):
        raise ValueError("CSV export requires canonical RangeIndex row order.")
    rows = []
    for position, column in enumerate(frame.columns):
        values = frame[column]
        dtype = str(values.dtype)
        if column in ("planning_seed_key", "metadata_seed_key"):
            logical, codec = "seed_key", "json_integer_tuple_4"
        elif filename == "transactions.csv" and column == "amount":
            logical, codec = "monetary_amount", "positive_cents_fixed_2"
        elif pd.api.types.is_datetime64_any_dtype(values.dtype):
            logical, codec = "timestamp", "iso8601"
        elif pd.api.types.is_bool_dtype(values.dtype):
            logical, codec = "boolean", "lowercase_boolean"
        elif pd.api.types.is_integer_dtype(values.dtype):
            logical, codec = "integer", "base10_integer"
        elif pd.api.types.is_float_dtype(values.dtype):
            logical, codec = "float", "binary64_17_significant_digits"
        elif pd.api.types.is_string_dtype(values.dtype) or dtype == "object":
            logical, codec = "string", "literal_utf8"
        else:
            raise ValueError(f"Unsupported export dtype: {filename}/{column}/{dtype}")
        if logical == "float" and np.isinf(values.to_numpy(dtype=float, na_value=np.nan)).any():
            raise ValueError("Infinite values cannot be exported as valid numbers.")
        for value in values.dropna():
            if isinstance(value, str) and value == EXPORT_NULL_TOKEN:
                raise ValueError("A literal string collides with the reserved CSV null token.")
            if logical == "string" and not isinstance(value, str):
                raise ValueError("Unsupported non-string object in export schema.")
            if logical == "seed_key" and (
                not isinstance(value, tuple) or len(value) != 4
                or any(not isinstance(item, (int, np.integer)) or isinstance(item, (bool, np.bool_)) or item < 0 for item in value)
            ):
                raise ValueError("Seed keys must be tuples of four nonnegative integers.")
        rows.append({
            "filename": filename, "position": position, "column": column,
            "pandas_dtype": dtype, "logical_type": logical, "csv_codec": codec,
            "is_key": column in primary_key, "nullable": bool(values.isna().any()),
            "null_count": int(values.isna().sum()),
        })
    return rows


def serialize_export_csv(frame, schema):
    """Return UTF-8 CSV bytes; to_csv receives no filename or disk handle.

    NaN is reserved for missing cells and is recognized by the existing
    notebook reader. The typed reader preserves other NA-like strings and
    empty historical reason strings using keep_default_na=False.
    """
    ordered = schema.sort_values("position")
    if frame.columns.tolist() != ordered["column"].tolist():
        raise ValueError("Serialization schema disagrees with frame columns.")
    encoded = frame.copy(deep=True)
    for spec in ordered.to_dict("records"):
        column, codec = spec["column"], spec["csv_codec"]
        if codec == "json_integer_tuple_4":
            encoded[column] = frame[column].map(
                lambda value: json.dumps([int(item) for item in value], separators=(",", ":"))
            )
        elif codec == "positive_cents_fixed_2":
            encoded[column] = frame[column].map(
                lambda value: f"{amount_to_cents(value) // 100}.{amount_to_cents(value) % 100:02d}"
            )
        elif codec == "iso8601":
            encoded[column] = frame[column].map(
                lambda value: pd.NA if pd.isna(value) else pd.Timestamp(value).isoformat()
            )
        elif codec == "lowercase_boolean":
            encoded[column] = frame[column].map(
                lambda value: pd.NA if pd.isna(value) else "true" if value else "false"
            )
    text = encoded.to_csv(
        index=False, sep=",", na_rep=EXPORT_NULL_TOKEN,
        float_format="%.17g", quoting=csv.QUOTE_MINIMAL, lineterminator="\n",
    )
    return text.encode("utf-8")


def deserialize_export_csv(payload, schema):
    """Schema-aware, lossless in-memory reader, including nullable integer cents."""
    ordered = schema.sort_values("position")
    raw = pd.read_csv(
        io.StringIO(payload.decode("utf-8")), dtype="string", keep_default_na=False,
        na_values=[EXPORT_NULL_TOKEN], skip_blank_lines=False,
    )
    if raw.columns.tolist() != ordered["column"].tolist():
        raise ValueError("CSV header disagrees with the export schema.")
    restored = pd.DataFrame(index=pd.RangeIndex(len(raw)))
    for spec in ordered.to_dict("records"):
        column, codec, dtype = spec["column"], spec["csv_codec"], spec["pandas_dtype"]
        values = raw[column]
        if values.isna().any() and not spec["nullable"]:
            raise ValueError("Unexpected null in a nonnullable export column.")
        if codec == "json_integer_tuple_4":
            def decode_seed(text):
                value = json.loads(text)
                if not isinstance(value, list) or len(value) != 4 or any(type(item) is not int or item < 0 for item in value):
                    raise ValueError("Invalid serialized seed key.")
                return tuple(value)
            restored[column] = values.map(decode_seed).astype(dtype)
        elif codec == "positive_cents_fixed_2":
            def decode_money(text):
                parts = text.split(".")
                if len(parts) != 2 or not parts[0].isdigit() or len(parts[1]) != 2 or not parts[1].isdigit():
                    raise ValueError("Transaction amount is not fixed two-decimal money.")
                cents = int(parts[0]) * 100 + int(parts[1])
                amount = cents / 100
                if cents <= 0 or amount_to_cents(amount) != cents:
                    raise ValueError("Invalid or lossy transaction monetary value.")
                return amount
            restored[column] = values.map(decode_money).astype(dtype)
        elif codec == "iso8601":
            restored[column] = pd.to_datetime(values, format="ISO8601", errors="raise").astype(dtype)
        elif codec == "lowercase_boolean":
            if not values.dropna().isin(("true", "false")).all():
                raise ValueError("Invalid serialized boolean.")
            restored[column] = values.map({"true": True, "false": False}).astype(dtype)
        elif codec == "base10_integer":
            restored[column] = pd.Series(
                [pd.NA if pd.isna(value) else int(value) for value in values], dtype=dtype
            )
        elif codec == "binary64_17_significant_digits":
            parsed = [np.nan if pd.isna(value) else float(value) for value in values]
            if np.isinf(np.asarray(parsed, dtype=float)).any():
                raise ValueError("Infinite value in numeric CSV column.")
            restored[column] = pd.Series(parsed, dtype=dtype)
        elif codec == "literal_utf8":
            restored[column] = values.astype(dtype)
        else:
            raise ValueError("Unknown CSV codec.")
    return restored


