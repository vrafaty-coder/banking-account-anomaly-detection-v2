INJECTION_MONTHS = (4, 5, 6)
INJECTIONS_PER_CELL = 10


def _selected_plan_order(plan):
    return (plan.month, SCENARIO_NAMES.index(plan.scenario), plan.account_id)


def _validate_selected_plans(selected):
    expected = {
        (month, scenario): INJECTIONS_PER_CELL
        for month in INJECTION_MONTHS for scenario in SCENARIO_NAMES
    }
    if len(selected) != sum(expected.values()):
        raise ValueError("Exactly 150 selected plans are required.")
    if len({plan.account_id for plan in selected}) != len(selected):
        raise ValueError("Selected accounts must be globally distinct.")
    if any(not plan.eligible or plan.rejection_reasons for plan in selected):
        raise ValueError("Selection contains a rejected candidate.")
    actual = Counter((plan.month, plan.scenario) for plan in selected)
    if actual != Counter(expected):
        raise ValueError(f"Selection does not meet the month/scenario quotas: {actual}")


def select_distinct_accounts(candidate_plans, *, allocation_rng=None):
    """Match all 150 slots using only eligibility and an independent ranking.

    One seeded permutation ranks account IDs before matching. Neither input
    order nor numeric account ID gives systematic priority. Reassignments
    occur only while solving the matching, never as application fallbacks.
    """
    allocation_rng = np.random.default_rng(ALLOCATION_SEED) if allocation_rng is None else allocation_rng
    lookup = {}
    for plan in candidate_plans:
        if plan.month not in INJECTION_MONTHS or plan.scenario not in SCENARIO_NAMES:
            raise ValueError("Candidate is outside the configured allocation cells.")
        key = (plan.account_id, plan.month, plan.scenario)
        if key in lookup:
            raise ValueError(f"Duplicate candidate key: {key}")
        if plan.eligible != (not plan.rejection_reasons):
            raise ValueError("Candidate eligibility and rejection reasons disagree.")
        lookup[key] = plan
    cells = [(month, scenario) for month in INJECTION_MONTHS for scenario in SCENARIO_NAMES]
    candidates = {cell: [] for cell in cells}
    for plan in lookup.values():
        if plan.eligible:
            candidates[(plan.month, plan.scenario)].append(plan.account_id)
    counts = {cell: len(values) for cell, values in candidates.items()}
    if any(count < INJECTIONS_PER_CELL for count in counts.values()):
        raise ValueError(f"Insufficient eligible accounts; no constraints relaxed: {counts}")

    account_ids = sorted({plan.account_id for plan in lookup.values()})
    ranked_accounts = allocation_rng.permutation(account_ids).tolist()
    rank = {account_id: position for position, account_id in enumerate(ranked_accounts)}
    for values in candidates.values():
        values.sort(key=lambda account_id: (rank[account_id], account_id))
    slots = [
        (month, scenario, ordinal)
        for month, scenario in cells for ordinal in range(INJECTIONS_PER_CELL)
    ]
    slots.sort(key=lambda slot: (counts[slot[:2]], slot[0], SCENARIO_NAMES.index(slot[1]), slot[2]))
    account_to_slot = {}

    def augment(slot, visited_accounts):
        for account_id in candidates[slot[:2]]:
            if account_id in visited_accounts:
                continue
            visited_accounts.add(account_id)
            previous = account_to_slot.get(account_id)
            if previous is None or augment(previous, visited_accounts):
                account_to_slot[account_id] = slot
                return True
        return False

    for slot in slots:
        if not augment(slot, set()):
            raise ValueError(
                "Globally distinct matching is infeasible; no seed or constraints changed. "
                f"Failed slot={slot}; matched={len(account_to_slot)}; eligible_counts={counts}"
            )
    selected = tuple(sorted(
        (lookup[(account_id, slot[0], slot[1])] for account_id, slot in account_to_slot.items()),
        key=_selected_plan_order,
    ))
    _validate_selected_plans(selected)
    return selected


def _planned_frame(context, rows, template):
    """Materialize recorded rows only, rejecting lossy monetary conversion."""
    records = []
    for row in rows:
        amount = row.amount_cents / 100
        if amount_to_cents(amount) != row.amount_cents:
            raise ValueError("Planned cents cannot be represented losslessly in the amount column.")
        debit = row.counterparty if row.direction == "inflow" else context.account_id
        credit = context.account_id if row.direction == "inflow" else row.counterparty
        records.append({
            "transaction_id": row.transaction_id, "timestamp": row.timestamp,
            "month": context.month, "debit_account": debit, "credit_account": credit,
            "amount": amount, "transaction_type": row.transaction_type, "channel": row.channel,
        })
    return pd.DataFrame.from_records(records, columns=template.columns).astype(template.dtypes.to_dict())


def _validate_applied_candidate(context, plan, actual):
    """Read actual endpoints and fields back, then run the Phase 2 invariants."""
    expected = _project_plan_rows(context, plan)
    expected_by_id = {row.transaction_id: row for row in expected}
    if not actual["transaction_id"].is_unique or set(actual["transaction_id"]) != set(expected_by_id):
        raise ValueError("Applied candidate transaction IDs differ from the recorded plan.")
    observed = {}
    for record in actual.itertuples(index=False):
        debit_is_account = record.debit_account == context.account_id
        credit_is_account = record.credit_account == context.account_id
        if debit_is_account == credit_is_account:
            raise ValueError("Applied row has invalid monitored endpoints.")
        if record.month != context.month:
            raise ValueError("Applied row moved to a different month.")
        counterparty = record.credit_account if debit_is_account else record.debit_account
        reference = expected_by_id[record.transaction_id]
        observed[record.transaction_id] = PlannedTransaction(
            record.transaction_id, amount_to_cents(record.amount),
            "outflow" if debit_is_account else "inflow", counterparty,
            record.transaction_type, record.timestamp, record.channel,
            reference.donor_transaction_id,
        )
    actual_updates = tuple(
        observed[row.transaction_id] for row in context.rows
        if observed[row.transaction_id] != row
    )
    actual_additions = tuple(observed[row.transaction_id] for row in plan.additions)
    actual_plan = replace(plan, updates=actual_updates, additions=actual_additions)
    validate_candidate_plan(context, actual_plan)
    if _project_plan_rows(context, actual_plan) != expected:
        raise ValueError("Applied transaction fields differ from the recorded candidate plan.")


def _validate_application_result(baseline, selected, before, after, contexts):
    _validate_selected_plans(selected)
    if tuple(after.columns) != tuple(before.columns) or not after.dtypes.equals(before.dtypes):
        raise ValueError("Application changed the transaction schema or dtypes.")
    if not after["transaction_id"].is_unique or after["transaction_id"].isna().any():
        raise ValueError("Final transaction IDs must be present and unique.")
    expected_added = [row.transaction_id for plan in selected for row in plan.additions]
    if len(after) != len(before) + len(expected_added):
        raise ValueError("Unexpected final transaction count.")
    if after["transaction_id"].tolist() != before["transaction_id"].tolist() + expected_added:
        raise ValueError("Original row order/IDs or recorded addition order changed.")

    accounts = set(baseline.accounts["account_id"])
    debit_monitored = after["debit_account"].isin(accounts)
    credit_monitored = after["credit_account"].isin(accounts)
    if not (debit_monitored ^ credit_monitored).all():
        raise ValueError("Each final transaction must have exactly one monitored endpoint.")
    counterparties = after["credit_account"].where(debit_monitored, after["debit_account"])
    if counterparties.isna().any() or counterparties.str.startswith("ACC").fillna(True).any():
        raise ValueError("Invalid final external endpoint.")
    if not after.loc[credit_monitored, "transaction_type"].isin(_INFLOW_TYPES).all():
        raise ValueError("Invalid inflow transaction type.")
    if not after.loc[debit_monitored, "transaction_type"].isin(_OUTFLOW_TYPES).all():
        raise ValueError("Invalid outflow transaction type.")
    if not after["channel"].isin(("batch", "mobile", "web", "branch")).all():
        raise ValueError("Invalid final channel.")
    if not after["month"].isin(range(1, N_MONTHS + 1)).all():
        raise ValueError("Invalid final relative month.")
    month_offset = START_MONTH + after["month"] - 2
    if (
        after["timestamp"].isna().any()
        or not after["timestamp"].dt.year.eq(START_YEAR + month_offset // 12).all()
        or not after["timestamp"].dt.month.eq(month_offset % 12 + 1).all()
    ):
        raise ValueError("Final timestamps disagree with relative months.")
    for amount in after["amount"]:
        amount_to_cents(amount)

    selected_keys = {(plan.account_id, plan.month) for plan in selected}
    before_owner = before["debit_account"].where(before["debit_account"].isin(accounts), before["credit_account"])
    untouched = np.array([
        (account_id, month) not in selected_keys
        for account_id, month in zip(before_owner, before["month"])
    ], dtype=bool)
    pd.testing.assert_frame_equal(
        before.loc[untouched], after.iloc[:len(before)].loc[untouched], check_exact=True
    )
    training = before["month"].isin((1, 2, 3))
    pd.testing.assert_frame_equal(
        before.loc[training], after.iloc[:len(before)].loc[training], check_exact=True
    )
    owner = after["debit_account"].where(debit_monitored, after["credit_account"])
    group_indices = after.groupby([owner, after["month"]], sort=False).indices
    for plan in selected:
        key = (plan.account_id, plan.month)
        positions = group_indices.get(key, ())
        _validate_applied_candidate(contexts[key], plan, after.iloc[list(positions)])


def validate_applied_injections(baseline, selected_plans, transactions):
    """Independent read-only validation against the immutable original baseline."""
    selected = tuple(sorted(selected_plans, key=_selected_plan_order))
    contexts = {
        (context.account_id, context.month): context
        for context in build_candidate_contexts(baseline, INJECTION_MONTHS)
    }
    _validate_application_result(baseline, selected, baseline.transactions, transactions, contexts)


def _labels_after_validation(baseline, selected):
    """Called only after the complete application has passed validation."""
    selected_by_key = {(plan.account_id, plan.month): plan.scenario for plan in selected}
    accounts = baseline.accounts["account_id"]
    labels = pd.MultiIndex.from_product(
        [accounts, range(1, N_MONTHS + 1)], names=["account_id", "month"]
    ).to_frame(index=False)
    labels["scenario"] = [
        selected_by_key.get((account_id, month), "normal")
        for account_id, month in zip(labels["account_id"], labels["month"])
    ]
    labels["is_injected_anomaly"] = labels["scenario"].ne("normal").astype(int)
    labels = labels[["account_id", "month", "is_injected_anomaly", "scenario"]]
    if labels.duplicated(["account_id", "month"]).any():
        raise ValueError("Duplicate ground-truth account-month key.")
    positive = labels.loc[labels["is_injected_anomaly"].eq(1)]
    if len(positive) != 150 or not positive["account_id"].is_unique:
        raise ValueError("Ground truth does not contain 150 distinct injected accounts.")
    expected = Counter({
        (month, scenario): INJECTIONS_PER_CELL
        for month in INJECTION_MONTHS for scenario in SCENARIO_NAMES
    })
    if Counter(zip(positive["month"], positive["scenario"])) != expected:
        raise ValueError("Ground truth does not match successful application quotas.")
    return labels


def apply_candidate_plans(baseline, selected_plans):
    """Apply recorded operations locally; fail without returning partial results.

    No planner or RNG is called. Original IDs and row order are retained;
    additions retain their candidate IDs. Labels are constructed last.
    """
    selected = tuple(sorted(selected_plans, key=_selected_plan_order))
    _validate_selected_plans(selected)
    before = baseline.transactions
    contexts = {
        (context.account_id, context.month): context
        for context in build_candidate_contexts(baseline, INJECTION_MONTHS)
    }
    used_ids = set(before["transaction_id"])
    for plan in selected:
        context = contexts.get((plan.account_id, plan.month))
        if context is None:
            raise ValueError("Selected plan references an unknown baseline account-month.")
        validate_candidate_plan(context, plan)
        for row in plan.additions:
            if row.transaction_id in used_ids:
                raise ValueError("Recorded addition ID collides with an existing or planned ID.")
            used_ids.add(row.transaction_id)

    working = before.copy(deep=True).set_index("transaction_id", drop=False)
    addition_frames = []
    for plan in selected:
        context = contexts[(plan.account_id, plan.month)]
        updates = _planned_frame(context, plan.updates, before).set_index("transaction_id", drop=False)
        for column in before.columns:
            if column != "transaction_id" and len(updates):
                working.loc[updates.index, column] = updates[column]
        additions = _planned_frame(context, plan.additions, before)
        original_ids = [row.transaction_id for row in context.rows]
        actual = pd.concat(
            [working.loc[original_ids].reset_index(drop=True), additions], ignore_index=True
        )
        _validate_applied_candidate(context, plan, actual)
        if len(additions):
            addition_frames.append(additions)
    after = pd.concat(
        [working.reset_index(drop=True)] + addition_frames, ignore_index=True
    )
    _validate_application_result(baseline, selected, before, after, contexts)
    labels = _labels_after_validation(baseline, selected)
    return after, labels


def inject_anomalies(baseline, candidate_plans, *, allocation_rng=None):
    """Allocate accepted candidates once, then apply recorded plans only."""
    selected = select_distinct_accounts(candidate_plans, allocation_rng=allocation_rng)
    return apply_candidate_plans(baseline, selected)

