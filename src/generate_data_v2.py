@dataclass(frozen=True)
class _FrozenFrame:
    """Immutable scalar records; each materialization returns a fresh frame."""

    columns: tuple
    dtypes: tuple
    rows: tuple

    @classmethod
    def from_frame(cls, frame):
        return cls(
            tuple(frame.columns),
            tuple(frame.dtypes),
            tuple(frame.itertuples(index=False, name=None)),
        )

    def to_frame(self):
        frame = pd.DataFrame.from_records(self.rows, columns=self.columns)
        return frame.astype(dict(zip(self.columns, self.dtypes)))


@dataclass(frozen=True)
class BaselineSnapshot:
    """Immutable baseline with stable IDs and defensive-copy accessors.

    These generated tables contain immutable scalar values only. Counterparty
    pools are stored as tuples, so no mutable DataFrame, list, or dict is kept.
    """

    _accounts: _FrozenFrame
    _counterparty_pools: tuple
    _transactions: _FrozenFrame

    @property
    def accounts(self):
        return self._accounts.to_frame()

    @property
    def counterparty_pools(self):
        return {
            account_id: list(pool)
            for account_id, pool in self._counterparty_pools
        }

    @property
    def transactions(self):
        return self._transactions.to_frame()


