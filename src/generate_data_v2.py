def run_v2_pipeline(
    *, baseline_seed=SEED, planning_seed=PLANNING_SEED,
    allocation_seed=ALLOCATION_SEED, metadata_seed=METADATA_SEED,
):
    """Run the approved pipeline in memory; never call main or any serializer."""
    protected_before = _protected_file_hashes()
    streams = make_rng_streams(baseline_seed, planning_seed, allocation_seed, metadata_seed)
    legacy_state = json.dumps(rng.bit_generator.state, sort_keys=True)
    baseline = generate_baseline(baseline_rng=streams["baseline"])
    accounts = baseline.accounts
    plans = build_candidate_plans(baseline, planning_seed=planning_seed, metadata_seed=metadata_seed)
    allocation_before = json.dumps(streams["allocation"].bit_generator.state, sort_keys=True)
    selected = select_distinct_accounts(plans, allocation_rng=streams["allocation"])
