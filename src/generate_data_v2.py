def build_account_month_aggregates(accounts, transactions):
    """Preserve the original account-month aggregate feature definitions."""

    # Identify the monitored account in each transaction.
    outflows = transactions.loc[
        transactions["debit_account"].str.startswith("ACC"),
        ["month", "debit_account", "credit_account", "amount"],
    ].copy()
    outflows.columns = ["month", "account_id", "counterparty", "amount"]
    outflows["direction"] = "outflow"

    inflows = transactions.loc[
        transactions["credit_account"].str.startswith("ACC"),
        ["month", "credit_account", "debit_account", "amount"],
    ].copy()
    inflows.columns = ["month", "account_id", "counterparty", "amount"]
    inflows["direction"] = "inflow"

    monitored = pd.concat([inflows, outflows], ignore_index=True)

    # Aggregate transaction counts, amounts, and counterparties.
    grouped = monitored.groupby(["account_id", "month"])

    base = grouped.agg(
        txn_count=("amount", "size"),
        unique_counterparties=("counterparty", "nunique"),
        max_transaction_amount=("amount", "max"),
    ).reset_index()

    sums = (
        monitored.assign(
            inflow_amount=np.where(
                monitored["direction"] == "inflow",
                monitored["amount"], 0.0
            ),
            outflow_amount=np.where(
                monitored["direction"] == "outflow",
                monitored["amount"], 0.0
            ),
        )
        .groupby(["account_id", "month"])
        .agg(
            inflow_sum=("inflow_amount", "sum"),
            outflow_sum=("outflow_amount", "sum"),
        )
        .reset_index()
    )

    averages = (
        monitored.groupby(["account_id", "month", "direction"])["amount"]
        .mean()
        .unstack("direction")
        .reindex(columns=["inflow", "outflow"])
        .rename(
            columns={
                "inflow": "inflow_avg",
                "outflow": "outflow_avg",
            }
        )
        .reset_index()
    )

    # Create all 1,000 x 6 account-month combinations, including
    # months in which an account has no transactions.
    grid = pd.MultiIndex.from_product(
        [accounts["account_id"], range(1, N_MONTHS + 1)],
        names=["account_id", "month"],
    ).to_frame(index=False)

    features = (
        grid.merge(base, on=["account_id", "month"], how="left")
        .merge(sums, on=["account_id", "month"], how="left")
        .merge(averages, on=["account_id", "month"], how="left")
    )

    for column in [
        "txn_count", "unique_counterparties", "max_transaction_amount",
        "inflow_sum", "outflow_sum",
    ]:
        features[column] = features[column].fillna(0)

    features["txn_count"] = features["txn_count"].astype(int)
    features["unique_counterparties"] = (
        features["unique_counterparties"].astype(int)
    )

    features["net_flow"] = features["inflow_sum"] - features["outflow_sum"]

    features["inflow_outflow_ratio"] = (
        features["inflow_sum"]
        / features["outflow_sum"].replace(0, np.nan)
    )

    features["zero_outflow_flag"] = (
        features["outflow_sum"] == 0
    ).astype(int)

    total_amount = features["inflow_sum"] + features["outflow_sum"]
    features["flow_concentration"] = (
        features["max_transaction_amount"]
        / total_amount.replace(0, np.nan)
    )

    features = features.drop(columns=["max_transaction_amount"])

    return features.sort_values(["account_id", "month"]).reset_index(drop=True)


